import { jsPDF } from 'jspdf';
import sharp from 'sharp';
import fs from 'fs';

const svgPath = '/Users/Staberman/Downloads/Logo sv.svg';
const outputTs = '/Users/Staberman/Desktop/PresupuestadoPro/lib/logo-watermark.ts';

const svgBuffer = fs.readFileSync(svgPath);

// Convert SVG to RGBA PNG at a reasonable size for watermark
const rawPng = await sharp(svgBuffer)
  .resize(600, 600, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

// Reduce alpha to 30%
const pixels = rawPng.data;
for (let i = 3; i < pixels.length; i += 4) {
  pixels[i] = Math.round(pixels[i] * 0.3);
}

// Create PNG from modified RGBA data
const finalPng = await sharp(pixels, { raw: { width: rawPng.info.width, height: rawPng.info.height, channels: 4 } })
  .png()
  .toBuffer();

const base64 = finalPng.toString('base64');
const dataUri = `data:image/png;base64,${base64}`;

const tsContent = `// Auto-generated by scripts/generate-watermark-ts.mjs
// Logo watermark at 30% opacity as a data URI (PNG, 600×600px)

export const LOGO_WATERMARK = '${dataUri}';
export const LOGO_WATERMARK_W = 600;
export const LOGO_WATERMARK_H = 600;
`;

fs.writeFileSync(outputTs, tsContent);
console.log('Watermark TS generated: ' + outputTs);
